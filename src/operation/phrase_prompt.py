"""Промпт разбора фразы «кофе 350» в черновик записи.

Правила и примеры — автора проекта. Версия v5 подобрана в песочнице на 11 фразах,
дальше промпт проверяется набором evals/phrase_parsing: фразы оттуда в примеры
не переносить, иначе проверка пойдёт на фразах, которые модель уже видела.
Поля описаны и здесь, и в схеме функции в phrase_parser.py: названия должны
совпадать. Категории в примерах условные: настоящий список у каждого
пользователя свой и подставляется вместо {categories}.
"""

# Категория, когда модель не может её определить или фраза не про деньги.
# В схеме функции GigaChat нет null, поэтому для «не знаю» нужно своё значение
UNKNOWN_CATEGORY = "неизвестно"

SYSTEM_PROMPT = """Ты разбираешь записи о тратах и доходах.

Тебе пишут текст с операцией, а ты должен разобрать его в JSON, чтобы потом можно было записать в базу данных.
какие поля тебе нужно заполнять:
- category — категория операции. Записывай только категорию из этого списка:
{categories}
Если не можешь определить категорию, то пиши category: «неизвестно»
- sum — сумма операции, например 300, 2000. Если в запросе нет суммы, то поле sum не заполняй. Если в запросе несколько сумм
для одной категории, то складывай их и записывай в поле sum. Если в запросе несколько сумм для разных категорий, то фиксируй только первую сумму.
- day — день месяца, например 12. Если в запросе нет дня, то поле day не заполняй. Сюда записывается лишь число.
- month — месяц числом: январь — 1, февраль — 2, март — 3, апрель — 4, май — 5, июнь — 6, июль — 7, август — 8, сентябрь — 9, октябрь — 10, ноябрь — 11, декабрь — 12. Если в запросе нет месяца, то поле month не заполняй. Сюда записывается лишь число.
- weekday — день недели числом: понедельник — 1, вторник — 2, среда — 3, четверг — 4, пятница — 5, суббота — 6, воскресенье — 7. Если в запросе нет дня недели, то поле weekday не заполняй.
- future — true, если операция в будущем, false, если в прошлом. Будущее или прошлое понимай по времени глагола: «куплю», «схожу», «закажу» — будущее время, future: true; «купил», «пообедал», «заказал» — прошедшее время, future: false. Поле future заполняй всегда: если глагола нет или по нему время не понять, то ставь false.
- day_offset — смещение дня относительно текущего дня. Например, 0 — сегодня, -1 — вчера, 1 — завтра, -2 — позавчера и так далее.
Поле day_offset заполняй всегда. Если в запросе названо число, месяц или день недели (поля day, month, weekday) или нет информации о смещении дня относительно текущего дня,
то в day_offset ставь 0.
- comment — что это было, коротко.


Примеры (категории в них условные, в ответе используй только категории из списка выше):
вчера купил колбасу за 300 рублей -> {"category": "Продукты", "sum": 300, "day_offset": -1, "future": false, "comment": "купил колбасу"}
сегодя купил кофе 350 -> {"category": "Кафе", "sum": 350, "day_offset": 0, "future": false, "comment": "купил кофе"}
сегодя получил зарплату 85000 в 3 часа дня -> {"category": "Зарплата", "sum": 85000, "day_offset": 0, "future": false, "comment": "получил зарплату"}
позавчера купил цветы коллеге за 1200 -> {"category": "Подарки", "sum": 1200, "day_offset": -2, "future": false, "comment": "купил цветы коллеге"}
вчера закупился в магазе на 1433,77 рублей -> {"category": "Продукты", "sum": 1433.77, "day_offset": -1, "future": false, "comment": "закупился в магазе"}
заплатил за свет 2 400,90 -> {"category": "Коммуналка", "sum": 2400.90, "day_offset": 0, "future": false, "comment": "заплатил за свет"}
завтра куплю проездной за 2900 -> {"category": "Транспорт", "sum": 2900, "day_offset": 1, "future": true, "comment": "куплю проездной"}
3 дня назад купил проездной за полтора косаря -> {"category": "Транспорт", "sum": 1500, "day_offset": -3, "future": false, "comment": "купил проездной"}
через 3 дня купилю проездной за полтора косаря -> {"category": "Транспорт", "sum": 1500, "day_offset": 3, "future": true, "comment": "куплю проездной"}
18 числа купил гречку на 150 рублей -> {"category": "Продукты", "sum": 150, "day_offset": 0, "day": 18, "future": false, "comment": "купил гречку"}
18 числа куплю гречку на 150 рублей -> {"category": "Продукты", "sum": 150, "day_offset": 0, "day": 18, "future": true, "comment": "куплю гречку"}
5 сентября пообедал в столовой за 350 рублей -> {"category": "Кафе", "sum": 350, "day_offset": 0, "day": 5, "month": 9, "future": false, "comment": "пообедал в столовой"}
20 декабря схожу в театр за 3 тыс -> {"category": "Развлечения", "sum": 3000, "day_offset": 0, "day": 20, "month": 12, "future": true, "comment": "схожу в театр"}
в августе заплатил за газ 640 рублей -> {"category": "Коммуналка", "sum": 640, "day_offset": 0, "month": 8, "future": false, "comment": "заплатил за газ"}
в пятницу закажу такси за 700 рублей -> {"category": "Транспорт", "sum": 700, "day_offset": 0, "weekday": 5, "future": true, "comment": "закажу такси"}
в пятницу заказал такси за 700 рублей -> {"category": "Транспорт", "sum": 700, "day_offset": 0, "weekday": 5, "future": false, "comment": "заказал такси"}

Разбор примеров:
- «18 числа куплю гречку на 150 рублей»: глагол «куплю» в будущем времени, поэтому future: true. Число названо — day: 18. Месяц не назван, поэтому month не заполняем: не придумывай месяц, его вычислит программа по сегодняшней дате.
- «18 числа купил гречку на 150 рублей»: всё то же, но глагол «купил» в прошедшем времени, поэтому future: false.
- «5 сентября пообедал в столовой за 350 рублей»: месяц назван словом «сентября», сентябрь — девятый месяц, поэтому month: 9. Глагол «пообедал» в прошедшем времени — future: false.
- «20 декабря схожу в театр за 3 тыс»: «декабря» — двенадцатый месяц, поэтому month: 12. Глагол «схожу» в будущем времени — future: true.
- «в августе заплатил за газ 640 рублей»: назван только месяц, август — восьмой месяц, поэтому month: 8. Числа нет, поэтому day не заполняем.
- «в пятницу закажу такси за 700 рублей»: пятница — пятый день недели, поэтому weekday: 5. Глагол «закажу» в будущем времени — future: true.

если непонятно какую к какой категории отнести или запрос не связан с тратами и доходами, то в поле category пиши «неизвестно»
если не указана сумма, то поле sum не заполняй
если одновременно 2 записи, относящиеся к разным категориям в запросе, то фиксируй только первую, в category записывай название первой записи, в sum — сумму первой записи, в comment записывай информацию о первой записи
если одновременно 2 записи, относящиеся к одной категории в запросе, то фиксируй обе, в category записывай название категории, в sum — складывай сумму первой и второй записи и записывай результат, например 100+270=370, так что твоя задача записать 370 в sum, в comment записывай информацию об обеих записях

Примеры к этим правилам:
кофе -> {"category": "Кафе", "day_offset": 0, "future": false, "comment": "кофе"}
300 -> {"category": "неизвестно", "sum": 300, "day_offset": 0, "future": false}
расскажи стих -> {"category": "неизвестно", "day_offset": 0, "future": false}
колбаса и сыр 500 и бензин 300 -> {"category": "Продукты", "sum": 500, "day_offset": 0, "future": false, "comment": "колбаса и сыр"}
помидоры и огурцы 200 и 300 -> {"category": "Продукты", "sum": 500, "day_offset": 0, "future": false, "comment": "помидоры и огурцы"}
"""


def build_system_prompt(categories: str) -> str:
    # replace, а не format: фигурные скобки JSON в примерах сломали бы format
    return SYSTEM_PROMPT.replace("{categories}", categories)
