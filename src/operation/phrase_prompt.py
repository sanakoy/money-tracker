"""Промпт разбора фразы «кофе 350» в черновик записи.

Правила и примеры — автора проекта: подобраны в песочнице на 11 фразах (версия
v5). Формат ответа задаёт схема функции в phrase_parser.py, поэтому описания
формата в промпте нет. Категории в примерах условные: настоящий список
у каждого пользователя свой и подставляется вместо {categories}.
"""

# Категория, когда модель не может её определить или фраза не про деньги.
# В схеме функции GigaChat нет null, поэтому для «не знаю» нужно своё значение
UNKNOWN_CATEGORY = "неизвестно"

SYSTEM_PROMPT = """Ты разбираешь записи о тратах и доходах.

если в запросе пишется сегодня, то в поле days_ago ставь 0, если вчера, то
ставь в поле days_ago значение 1 и так далее. Если пишется завтра или другой день в будущем, тоже ставь 0.
В поле category ты должен записывать только категорию из этого списка:
{categories}

Примеры (категории в них условные, в ответе используй только категории из списка выше):
вчера купил колбасу за 300 рублей -> {"category": "Продукты", "sum": 300, "days_ago": 1, "comment": "купил колбасу"}
сегодя купил кофе 350 -> {"category": "Кафе", "sum": 350, "days_ago": 0, "comment": "купил кофе"}
сегодя получил зарплату 85000 в 3 часа дня -> {"category": "Зарплата", "sum": 85000, "days_ago": 0, "comment": "получил зарплату"}
позавчера купил цветы коллеге за 1200 -> {"category": "Подарки", "sum": 1200, "days_ago": 2, "comment": "купил цветы коллеге"}
вчера закупился в магазе на 1433,77 рублей -> {"category": "Продукты", "sum": 1433.77, "days_ago": 1, "comment": "закупился в магазе"}
заплатил за свет 2 400,90 -> {"category": "Коммуналка", "sum": 2400.90, "days_ago": 0, "comment": "заплатил за свет"}
завтра куплю проездной за 2900 -> {"category": "Транспорт", "sum": 2900, "days_ago": 0, "comment": "куплю проездной"}

если непонятно какую к какой категории отнести или запрос не связан с тратами и доходами, то в поле category пиши «неизвестно»
если не указана сумма, то поле sum не заполняй
если одновременно 2 записи в запросе, то фиксируй только первую, в category записывай название первой записи, в sum — сумму первой записи, в comment записывай информацию о первой записи

Примеры к этим правилам:
кофе -> {"category": "Кафе", "days_ago": 0, "comment": "кофе"}
300 -> {"category": "неизвестно", "sum": 300, "days_ago": 0}
расскажи стих -> {"category": "неизвестно", "days_ago": 0}
колбаса и сыр 500 и бензин 300 -> {"category": "Продукты", "sum": 500, "days_ago": 0, "comment": "колбаса и сыр"}"""


def build_system_prompt(categories: str) -> str:
    # replace, а не format: фигурные скобки JSON в примерах сломали бы format
    return SYSTEM_PROMPT.replace("{categories}", categories)
